-- 删除旧表（如存在）
DROP TABLE IF EXISTS missing_data;
DROP TABLE IF EXISTS price_policies;
DROP TABLE IF EXISTS sources;
DROP TABLE IF EXISTS provinces;

-- ============================================================
-- 1. 行政区域表
-- ============================================================
CREATE TABLE provinces (
    id INTEGER PRIMARY KEY,
    province_code TEXT NOT NULL,
    province_name TEXT NOT NULL,
    region TEXT NOT NULL,
    grid_company TEXT,
    region_note TEXT
);

-- ============================================================
-- 2. 数据来源表
-- ============================================================
CREATE TABLE sources (
    id INTEGER PRIMARY KEY,
    source_name TEXT NOT NULL,
    source_url TEXT NOT NULL,
    issuing_authority TEXT NOT NULL,
    publish_date TEXT,
    collect_date TEXT,
    reliability TEXT,
    notes TEXT
);

-- ============================================================
-- 3. 分时电价政策表
-- ============================================================
CREATE TABLE price_policies (
    id INTEGER PRIMARY KEY,
    province_id INTEGER NOT NULL,
    season_type TEXT NOT NULL,
    user_type TEXT NOT NULL,
    voltage_level TEXT,
    original_period_name TEXT NOT NULL,
    standard_category TEXT NOT NULL,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    price_yuan_kwh REAL,
    price_basis TEXT,
    source_id INTEGER NOT NULL,
    policy_effective_date TEXT,
    policy_expire_date TEXT,
    data_status TEXT NOT NULL DEFAULT '真实数据',
    caliber_note TEXT,
    FOREIGN KEY (province_id) REFERENCES provinces(id),
    FOREIGN KEY (source_id) REFERENCES sources(id)
);

-- ============================================================
-- 4. 缺失数据记录表
-- ============================================================
CREATE TABLE missing_data (
    id INTEGER PRIMARY KEY,
    province_id INTEGER NOT NULL,
    missing_field TEXT NOT NULL,
    reason TEXT,
    search_effort TEXT,
    next_step TEXT,
    FOREIGN KEY (province_id) REFERENCES provinces(id)
);

-- ============================================================
-- 5. 创建索引
-- ============================================================
CREATE INDEX idx_price_province ON price_policies(province_id);
CREATE INDEX idx_price_season ON price_policies(season_type);
CREATE INDEX idx_price_user_type ON price_policies(user_type);
CREATE INDEX idx_price_category ON price_policies(standard_category);
CREATE INDEX idx_missing_province ON missing_data(province_id);

